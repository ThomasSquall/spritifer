#!/usr/bin/env python3
"""Bakes Pixel Operator into src/core/game/fontPixelOperator.ts.

Usage: build-pixel-operator.py path/to/PixelOperator.ttf
Font: https://www.dafont.com/pixel-operator.font (Jayvee Enaguas, CC0 1.0). Needs fontTools.

The outlines sit on a 100-unit grid (16 px per em), so sampling pixel centres gives the exact bitmap.
"""
import json
import sys
from math import ceil, floor
from pathlib import Path

from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

UNIT = 100  # font units per pixel
OUT = Path(__file__).resolve().parent.parent / 'src/core/game/fontPixelOperator.ts'


def contours(glyph_set, name):
    pen = DecomposingRecordingPen(glyph_set)
    glyph_set[name].draw(pen)
    out, cur = [], []
    for op, args in pen.value:
        if op == 'moveTo':
            cur = [args[0]]
        elif op == 'lineTo':
            cur.append(args[0])
        elif op in ('closePath', 'endPath'):
            out.append(cur)
        else:
            raise SystemExit(f'{name}: unexpected curve ({op}), not a pixel outline')
    return out


def winding(polys, x, y):
    w = 0
    for poly in polys:
        for (x0, y0), (x1, y1) in zip(poly, poly[1:] + poly[:1]):
            if (y0 <= y) != (y1 <= y) and x < x0 + (y - y0) * (x1 - x0) / (y1 - y0):
                w += 1 if y1 > y0 else -1
    return w


def bitmap(polys):
    """(left, top, rows): top is relative to the baseline, y down; each row is a mask with bit 0 = leftmost pixel."""
    pts = [p for poly in polys for p in poly]
    if not pts:
        return 0, 0, []
    x0 = floor(min(p[0] for p in pts) / UNIT)
    x1 = ceil(max(p[0] for p in pts) / UNIT)
    y0 = floor(min(p[1] for p in pts) / UNIT)
    y1 = ceil(max(p[1] for p in pts) / UNIT)
    rows = []
    for py in range(y1 - 1, y0 - 1, -1):
        mask = 0
        for px in range(x0, x1):
            if winding(polys, (px + 0.5) * UNIT, (py + 0.5) * UNIT):
                mask |= 1 << (px - x0)
        rows.append(mask)
    return x0, -y1, rows


def main(ttf):
    font = TTFont(ttf)
    glyph_set = font.getGlyphSet()
    entries = {}
    for code, name in sorted(font.getBestCmap().items()):
        if code < 32 or 127 <= code < 160:
            continue
        left, top, rows = bitmap(contours(glyph_set, name))
        advance = font['hmtx'][name][0]
        if advance % UNIT:
            raise SystemExit(f'{name}: advance {advance} is off the pixel grid')
        entries[chr(code)] = f"{int(advance // UNIT)};{left};{top};{','.join(f'{r:x}' for r in rows)}"
    body = ',\n'.join(f'  {json.dumps(ch, ensure_ascii=False)}: {json.dumps(v)}' for ch, v in entries.items())
    OUT.write_text(
        '// Generated by scripts/build-pixel-operator.py. Do not edit.\n'
        '// Pixel Operator by Jayvee Enaguas (HarvettFox96), CC0 1.0: https://www.dafont.com/pixel-operator.font\n\n'
        '/** Character → "advance;left;top;rows": top is relative to the baseline, rows are hex masks (bit 0 = leftmost). */\n'
        f'export const PIXEL_OPERATOR_GLYPHS: Record<string, string> = {{\n{body},\n}};\n',
        encoding='utf8',
    )
    print(f'{len(entries)} glyphs written to {OUT}')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
